import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const root = mkdtempSync(join(tmpdir(), 'lattice-callouts-'));
for (const dir of ['content/posts', 'content/data', 'templates']) mkdirSync(join(root, dir), { recursive: true });
writeFileSync(join(root, 'collections.cfg'), '[posts]\ndir = content/posts\nschema = title:String\n');
writeFileSync(join(root, 'content/lattice.conf'), 'title = Research\nbase_url = https://example.test\ntemplates_dir = templates\ncollections_file = collections.cfg\noutput_dir = dist\n');
writeFileSync(join(root, 'templates/page.html'), '<article>{{content}}</article>');
const source = join(root, 'content/index.md');
writeFileSync(source, '---\ntitle: Research\n---\n> [!warning] Read [[source|the source]]\n> [[source#evidence|Evidence]] matters.\n>\n> > [!tip]+ Nested\n> > Keep **context**.\n');
writeFileSync(join(root, 'content/source.md'), '---\ntitle: Source\n---\n> [!note]\n> ## Evidence\n> Findings.\n\n## Evidence\n');
const cli = fileURLToPath(new URL('../_build/js/debug/build/kurisu/lattice/cmd/main/main.js', import.meta.url));
const run = (...args) => spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: 'utf8', timeout: 30_000 });
let result = run('check', '--format', 'json');
assert.equal(result.status, 0, result.stdout + result.stderr);
assert.equal(existsSync(join(root, 'dist')), false);
result = run('build', '--strict-wikilinks');
assert.equal(result.status, 0, result.stdout + result.stderr);
const html = readFileSync(join(root, 'dist/index.html'), 'utf8');
assert.ok(html.includes('class="callout callout-warning"'));
assert.ok(html.includes('href="/source/"') && html.includes('href="/source/#evidence"'));
assert.ok(html.includes('<details class="callout callout-tip" open>'));
const target = readFileSync(join(root, 'dist/source/index.html'), 'utf8');
assert.ok(target.includes('id="evidence"') && target.includes('id="evidence-2"'));
writeFileSync(source, '---\ntitle: Research\n---\n> [!warning] Read [[missing]]\n> [[source#gone]]\n');
result = run('check', '--format', 'json');
assert.equal(result.status, 1, result.stdout + result.stderr);
const data = JSON.parse(result.stdout.slice(result.stdout.indexOf('{\n  "violations"')));
assert.deepEqual(data.violations.filter(v => v.kind === 'broken_wikilink').map(v => v.line), [4, 5]);
assert.equal(readFileSync(join(root, 'dist/index.html'), 'utf8'), html);
console.log('Obsidian callouts: title/body links, nested blocks, final headings, source diagnostics and read-only check passed');
